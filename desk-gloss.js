function deskTipShow(a,pinned){
  const id=a&&a.dataset&&a.dataset.g,T=_dkTip;
  if(!id||!deskGlossItem(id)||deskGlossIsOpen()||!deskActive())return;
  const el=deskTipEl();clearTimeout(T.tShow);clearTimeout(T.tHide);
  if(T.anchor&&T.anchor!==a&&T.anchor.tagName==='BUTTON')T.anchor.setAttribute('aria-expanded','false');
  if(T.id!==id||el.hidden)el.innerHTML=deskGlossTipHTML(id);
  T.id=id;T.anchor=a;T.pinned=!!pinned;T.idx=deskTipAnchors(id).indexOf(a);
  el.hidden=false;deskTipPlace();
  if(a.tagName==='BUTTON')a.setAttribute('aria-expanded','true');
}
function deskTipPlace(){
  const el=document.getElementById('dkTip'),a=_dkTip.anchor;if(!el||el.hidden||!a)return;
  const r=a.getBoundingClientRect();
  if(!r.width&&!r.height){deskTipHide(false);return;}   // метка скрыта (свёрнутый блок)
  const de=document.documentElement,p=deskTipPos(r,el.offsetWidth,el.offsetHeight,de.clientWidth||window.innerWidth,de.clientHeight||window.innerHeight);   // без полосы прокрутки
  el.style.left=p.left+'px';el.style.top=p.top+'px';
}
// restore — вернуть фокус на кнопку ⓘ (Esc с клавиатуры).
function deskTipHide(restore){
  const T=_dkTip,el=document.getElementById('dkTip'),a=T.anchor;
  clearTimeout(T.tShow);clearTimeout(T.tHide);clearTimeout(T.tHold);T.hold=null;
  T.id=null;T.anchor=null;T.pinned=false;
  if(!el||el.hidden)return;
  el.hidden=true;
  if(a&&a.tagName==='BUTTON'){a.setAttribute('aria-expanded','false');if(restore&&a.isConnected)try{a.focus({preventScroll:true});}catch(e){}}
}
// ⓘ: закреплённая подсказка; повторный клик по той же кнопке — скрыть. С клавиатуры — фокус на «Подробнее».
function deskTipToggle(b,kbd){
  const T=_dkTip;
  if(T.anchor===b&&T.pinned&&deskTipIsOpen()){deskTipHide(kbd);return;}
  deskTipShow(b,true);
  if(kbd){const m=document.querySelector('#dkTip .dk-tip-more');if(m)try{m.focus({preventScroll:true});}catch(e){}}
}
function deskTipMore(){
  const id=_dkTip.id,a=_dkTip.anchor;if(!id)return;
  deskTipHide(false);
  if(a&&a.isConnected&&a.tagName==='BUTTON')try{a.focus({preventScroll:true});}catch(e){}   // словарь вернёт фокус сюда
  deskGlossOpen(id);
}
// После перерисовки экрана (deskPaint): метка заменена новым узлом — найти ту же по индексу, иначе скрыть.
function deskTipAfterPaint(){
  const T=_dkTip;if(!deskTipIsOpen())return;
  if(T.anchor&&T.anchor.isConnected){deskTipPlace();return;}
  const n=deskTipAnchors(T.id)[T.idx];
  if(!n){deskTipHide(false);return;}
  T.anchor=n;if(n.tagName==='BUTTON')n.setAttribute('aria-expanded','true');
  deskTipPlace();
}
function deskTipBoot(){
  if(typeof document==='undefined'||!document.addEventListener)return;
  const T=_dkTip,tipEl=()=>document.getElementById('dkTip');
  // Мышь (pointerType, а не hover-медиа: касание шлёт совместимые mouseover, их не ловим).
  document.addEventListener('pointerover',e=>{
    if(e.pointerType!=='mouse'||!deskActive()||deskGlossIsOpen())return;
    const el=tipEl(),open=deskTipIsOpen();
    if(open&&el.contains(e.target)){clearTimeout(T.tHide);return;}
    const a=deskTipAnchorOf(e.target);if(!a)return;
    if(a===T.anchor){clearTimeout(T.tHide);return;}
    if(open&&T.pinned)return;   // закреплённую (ⓘ, долгое нажатие) наведение не подменяет
    clearTimeout(T.tShow);
    T.tShow=setTimeout(()=>{if(a.isConnected&&a.matches(':hover'))deskTipShow(a,false);},open?0:DK_TIP.showMs);   // уже открыта — переключаем сразу
  });
  document.addEventListener('pointerout',e=>{
    if(e.pointerType!=='mouse'||!deskTipIsOpen()||T.pinned)return;
    const el=tipEl(),to=e.relatedTarget,inside=n=>!!n&&(el.contains(n)||(!!T.anchor&&T.anchor.contains(n)));
    if(inside(e.target)&&!inside(to)){clearTimeout(T.tHide);T.tHide=setTimeout(()=>deskTipHide(false),DK_TIP.hideMs);}
  });
  // Касание: долгое нажатие на метке; сдвиг пальца (прокрутка) или отпускание раньше срока — отмена.
  document.addEventListener('pointerdown',e=>{
    if(e.pointerType!=='touch')return;
    T.touchAt=Date.now();clearTimeout(T.tHold);T.hold=null;
    const a=deskTipAnchorOf(e.target);if(!a||!deskActive()||deskGlossIsOpen())return;
    T.hold={a,x:e.clientX,y:e.clientY};
    T.tHold=setTimeout(()=>{const h=T.hold;T.hold=null;if(h&&h.a===a&&a.isConnected){T.lp=true;deskTipShow(a,true);}},DK_TIP.holdMs);
  },{passive:true});
  document.addEventListener('pointermove',e=>{const h=T.hold;if(h&&e.pointerType==='touch'&&Math.hypot(e.clientX-h.x,e.clientY-h.y)>DK_TIP.moveTol){clearTimeout(T.tHold);T.hold=null;}},{passive:true});
  ['pointerup','pointercancel'].forEach(t=>document.addEventListener(t,e=>{
    if(e.pointerType!=='touch')return;
    if(T.hold){clearTimeout(T.tHold);T.hold=null;}
    if(T.lp){T.lp=false;T.lpUntil=Date.now()+DK_TIP.lpClickMs;}
  },{passive:true}));
  // Системное меню долгого нажатия на метке не нужно (только после касания — правый клик мышью не трогаем).
  document.addEventListener('contextmenu',e=>{if(Date.now()-T.touchAt<1500&&deskTipAnchorOf(e.target))e.preventDefault();});
  // Раньше обработчиков #desk: клик после долгого нажатия не открывает строку; клик мимо подсказки её скрывает.
  document.addEventListener('click',e=>{
    if(Date.now()<T.lpUntil){T.lpUntil=0;e.preventDefault();e.stopPropagation();return;}
    if(!deskTipIsOpen())return;
    const el=tipEl();if(el.contains(e.target))return;
    if(T.anchor&&T.anchor.contains(e.target)&&e.target.closest('[data-a="gtip"]'))return;   // ⓘ переключит сама
    deskTipHide(false);
  },true);
  document.addEventListener('scroll',()=>{if(deskTipIsOpen())deskTipHide(false);},{passive:true,capture:true});
  window.addEventListener('resize',()=>{if(deskTipIsOpen())deskTipHide(false);});
}
deskTipBoot();
